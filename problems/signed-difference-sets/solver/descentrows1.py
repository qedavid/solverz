"""P18 M1 rows: open rows killed by one step of Schmidt's field descent at an odd prime (`FieldDescent.lean`).

A row dies on a cyclic quotient C_m (m | exp G, c = v/m) at an odd prime p with p^2 | m when, for every prime q | n
(n = k - lambda), 1 + m/p is a power of q modulo the q-free part of m, and m (m/p) c^2 < phi(m) n
(`FieldDescentCert.Kills`). Independent of `scratch/p18/rows.py`: the q-free part and the powers of q are recomputed
here, and every candidate is also checked on the `exists` rows (none may die).
`python solver/descentrows1.py` writes `lean/SignedDifferenceSets/FieldDescentRows.lean` and
`scratch/p18/settle-m1.tsv`; `--check` only prints. Run from the problem folder.
"""

import csv
import math
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "lean" / "SignedDifferenceSets" / "FieldDescentRows.lean"
TSV = ROOT / "scratch" / "p18" / "settle-m1.tsv"
KEY = re.compile(r"SDS\((\d+),(\d+),(-?\d+),\[([\d,]+)\]\)")
OPEN, EXISTS = "open", "exists"
NL = "\n"


def factor(n):
    """Prime factorization as {p: e} by trial division."""
    out, d = {}, 2
    while d * d <= n:
        while n % d == 0:
            out[d] = out.get(d, 0) + 1
            n //= d
        d += 1
    if n > 1:
        out[n] = out.get(n, 0) + 1
    return out


def totient(m):
    return sum(1 for x in range(1, m + 1) if math.gcd(x, m) == 1)


def q_free(m, q):
    """m with every factor q removed, and the removed power."""
    a = 0
    while m % q == 0:
        m //= q
        a += 1
    return m, a


def is_power_mod(x, q, mod):
    """Is x congruent to some q^e (e >= 0) modulo mod (q prime to mod)?"""
    seen, y = set(), 1 % mod
    while y not in seen:
        if y == x % mod:
            return True
        seen.add(y)
        y = y * q % mod
    return False


def step_ok(m, p, n):
    """One descent step m -> m/p at odd p: p^2 | m and 1 + m/p a power of each q | n mod its q-free part."""
    if p == 2 or m % (p * p):
        return False
    t = 1 + m // p
    return all(is_power_mod(t, q, q_free(m, q)[0]) for q in factor(n))


def cert(v, k, lam, ms):
    """First (m, p) by increasing m, then p, killing the row, or None."""
    n = k - lam
    if n <= 0:
        return None
    w = math.lcm(*ms)
    for m in range(2, w + 1):
        if w % m:
            continue
        c = v // m
        for p in sorted(factor(m)):
            if step_ok(m, p, n) and m * (m // p) * c * c < totient(m) * n:
                return m, p
    return None


def form(ms, m):
    """Coefficients A of a surjective form Grp ms -> ZMod m and a preimage P of 1 (CRT)."""
    g = [1] * len(ms)
    for p, e in factor(m).items():
        q = p ** e
        i = next(i for i, x in enumerate(ms) if x % q == 0)
        g[i] *= q
    A = [m // gi if gi > 1 else 0 for gi in g]
    P = [pow(m // gi, -1, gi) if gi > 1 else 0 for gi in g]
    assert all(a * x % m == 0 for a, x in zip(A, ms)), (ms, m, A)
    assert sum(a * x for a, x in zip(A, P)) % m == 1 % m, (ms, m, A, P)
    return A, P


def lst(xs):
    return "[" + ", ".join(map(str, xs)) + "]"


def rows_of(status):
    for r in csv.DictReader(open(ROOT / "instances.csv", encoding="utf-8")):
        if r["status"] == status:
            v, k, lam, ms = KEY.fullmatch(r["key"]).groups()
            yield r["id"], int(v), int(k), int(lam), [int(x) for x in ms.split(",")]


def collect():
    rows = []
    for i, v, k, lam, ms in rows_of(OPEN):
        hit = cert(v, k, lam, ms)
        if hit:
            m, p = hit
            A, P = form(ms, m)
            rows.append((i, ms, k, lam, m, p, A, P))
    bad = [(i, cert(v, k, lam, ms)) for i, v, k, lam, ms in rows_of(EXISTS) if cert(v, k, lam, ms)]
    return rows, bad


def render(rows):
    body = []
    for i, ms, k, lam, m, p, A, P in rows:
        body.append(f"""/-- {i}: SDS{tuple([math.prod(ms), k, lam])} on {lst(ms)}, quotient `ZMod {m}`, `p = {p}`. -/
theorem fieldDescentKill_{i} :
    FieldDescentCert.Kills ⟨{i[1:]}, {lst(ms)}, {k}, {lam}⟩ ⟨{m}, {p}, {lst(A)}, {lst(P)}⟩ := by
  decide +kernel
""")
    items = ("," + NL).join(f"  (⟨{i[1:]}, {lst(ms)}, {k}, {lam}⟩, ⟨{m}, {p}, {lst(A)}, {lst(P)}⟩)"
                           for i, ms, k, lam, m, p, A, P in rows)
    proof = "List.forall_mem_nil _"
    for i, *_ in reversed(rows):
        proof = f"List.forall_mem_cons.2 ⟨fieldDescentKill_{i},{NL}    {proof}⟩"
    return f"""module

public import SignedDifferenceSets.FieldDescent

/-!
# Rows killed by one step of Schmidt's field descent (P18, M1)

{len(rows)} open rows, each with a cyclic quotient `ZMod m` (the form `A`, a preimage `P` of `1`) and an odd
prime `p`, `p² ∣ m`, such that `FieldDescentCert.Kills` holds; each row is checked by its own
`decide +kernel`. Generated by `solver/descentrows1.py`.
-/

@[expose] public section

namespace SignedDifferenceSets

{NL.join(body)}
/-- The rows and their certificates. -/
def fieldDescentRows : List (Row × FieldDescentCert) := [
{items}]

theorem fieldDescentRows_kill : ∀ x ∈ fieldDescentRows, x.2.Kills x.1 :=
  {proof}

/-- No row of `fieldDescentRows` has an SDS. -/
theorem fieldDescentRows_not_hasSDS {{x : Row × FieldDescentCert}} (hx : x ∈ fieldDescentRows)
    (inst : Fintype (Grp x.1.ms)) : ¬ @HasSDS (Grp x.1.ms) _ inst x.1.k x.1.lam :=
  FieldDescentCert.not_hasSDS (fieldDescentRows_kill x hx) inst

end SignedDifferenceSets
"""


def main():
    rows, bad = collect()
    print(len(rows), "open rows killed;", len(bad), "exists rows killed", bad[:5])
    spike = ROOT / "scratch" / "p18" / "rows.out"
    if spike.exists():
        one = {ln.split()[0] for ln in spike.read_text(encoding="utf-8").splitlines()
               if re.search(r"chain=\[\d+\] ", ln)}
        mine = {r[0] for r in rows}
        print("rows.out one-step rows:", len(one), "| only here:", sorted(mine - one), "| only there:",
              sorted(one - mine))
    if bad or "--check" in sys.argv:
        return
    OUT.write_text(render(rows), encoding="utf-8", newline=NL)
    TSV.write_text("".join(f"{r[0]}\tnone\tP18 M1; FieldDescentRows\t"
                           f"SignedDifferenceSets.fieldDescentRows_not_hasSDS{NL}" for r in rows),
                   encoding="utf-8", newline=NL)
    print("wrote", OUT.name, "and", TSV.name)


if __name__ == "__main__":
    main()
