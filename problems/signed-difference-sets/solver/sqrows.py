"""I23, k - lam = p^2: rows killed by Tomography.not_hasSDS_grp_sq (TomographySquare.lean), no lists.

sqrows.py --scan: every row of instances.csv with n = k - lam = p^2 (p prime), p-rank >= 2, s = p q (q > 0),
c p < q + p - 1 (c = v / p^2) and p not dividing q + 1, with its status.
sqrows.py <id> [<id> ...]: writes lean/SignedDifferenceSets/TomographySquareRows/N<id>.lean for each (phi = reduction
mod p of two factors divisible by p, as tomoquot.py). tomoquot.py and tomorows.py are imported, not changed.
"""
import csv
import math
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import tomoquot as Q  # noqa: E402
import tomorows as T  # noqa: E402

DIR = "lean/SignedDifferenceSets/TomographySquareRows"


def is_prime(n):
    return n > 1 and all(n % d for d in range(2, math.isqrt(n) + 1))


def data(v, k, lam, ms):
    """(p, c, s, q) when the theorem applies, else None."""
    n = k - lam
    if n <= 0:
        return None
    p = math.isqrt(n)
    if p * p != n or not is_prime(p) or sum(m % p == 0 for m in ms) < 2:
        return None
    s2 = k + lam * (v - 1)
    s = math.isqrt(s2) if s2 >= 0 else -1
    if s < 0 or s * s != s2 or s % p:
        return None
    q, c = s // p, v // (p * p)
    if c * p < q + p - 1 and (q + 1) % p:
        return p, c, s, q
    return None


def scan():
    for r in csv.DictReader(open("instances.csv", encoding="utf-8")):
        m = re.match(r"SDS\((\d+),(-?\d+),(-?\d+),\[([\d,]+)\]\)", r["key"])
        if not m:
            continue
        v, k, lam = int(m[1]), int(m[2]), int(m[3])
        ms = [int(x) for x in m[4].split(",")]
        d = data(v, k, lam, ms)
        if d:
            print(r["id"], r["status"], r["key"], "p=%d c=%d s=%d q=%d" % d)


def write_row(id_):
    v, k, lam, ms, status = Q.row_of(id_)
    d = data(v, k, lam, ms)
    assert d, id_
    p, c, s, q = d
    A, P = Q.forms(ms, p)
    g = Q.group_name(ms)
    text = f"""module

public import SignedDifferenceSets.TomographySquare

/-!
# {id_}: no SDS ({v}, {k}, {lam}) in {g} (I23, `k − λ = {p}²`)

Reduction mod {p} of two factors maps onto `ZMod {p} × ZMod {p}` with fibres of `c = {c}`;
`s = {s} = {p}·{q}`. Every line contraction is constant mod {p} (`congr_of_autocorr_sq`), hence
`≡ {q} ± 1`; the box `{c}·{p} < {q} + {p} − 1` leaves `≡ {q + 1}`, and the line identity at `0` would
need `{p} ∣ {q + 1}` (`Tomography.not_hasSDS_grp_sq`). Generated by `solver/sqrows.py`.
-/

@[expose] public section

namespace SignedDifferenceSets.TomographySquareRows.{id_}

open Tomography

/-- `{p}` is prime. -/
local instance fact : Fact (Nat.Prime {p}) := ⟨by norm_num⟩

/-- {id_}: `{g}` has no signed difference set
with parameters ({v}, {k}, {lam}). -/
theorem not_hasSDS : ¬ HasSDS ({g}) {k} {lam} :=
  not_hasSDS_grp_sq (ms := {T.flat(ms)}) {p}
    (A := {T.flat(A)}) (P := {T.flat(P)})
    (by decide) (by decide) _ (c := {c}) (s := {s}) (q := {q}) (by decide) (by norm_num)
    (by norm_num) (by norm_num) (by norm_num) (by norm_num)

end SignedDifferenceSets.TomographySquareRows.{id_}
"""
    os.makedirs(DIR, exist_ok=True)
    path = f"{DIR}/{id_}.lean"
    open(path, "w", encoding="utf-8", newline="\n").write(text)
    for i, line in enumerate(text.split("\n"), 1):
        assert len(line) <= 100, (path, i, len(line))
    print(path, status, f"p={p} c={c} s={s} q={q}")


if __name__ == "__main__":
    if sys.argv[1:] == ["--scan"]:
        scan()
    else:
        for id_ in sys.argv[1:]:
            write_row(id_)
