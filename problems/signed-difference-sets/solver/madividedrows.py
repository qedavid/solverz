"""Rows killed by C34 (the divided contraction below a Ma quotient), written as Lean.

`madividedrows.py [ids...]`: reads the kills of `x_ma_divided` (`scratch/x_ma_divided.out`: `id key v KILL p j H' nodes`) at odd p
that C33 does not already settle (`scratch/maedge/settle.tsv`), rebuilds each certificate (`MaDivCert`: H = ZMod (p^j) × K with K
the p'-parts of H', forms and preimages as `marows.py`), and writes `lean/SignedDifferenceSets/MaDividedRows/N<id>.lean` (split
into part modules by `answer.write_search` when the search is large) and `scratch/maedge/settle-c34.tsv`. Mirrors
`MaDivCert.Valid`. Standard library only; nothing is written on import.
"""
import math
import re
import sys
from pathlib import Path

from answer import BATCH_NODES, write_search
from macombrows import ma_pairs
from marows import conj_exp, crt, is_prime_td, lst, map_ok, surj_cert, vp

# the join's coverage check is quadratic in the prefixes: N19445 needs 2,737 at the default depth
SKIP = {"N19445"}
ROOT = Path(__file__).resolve().parent.parent
KILLS = ROOT / "scratch" / "x_ma_divided.out"
C33 = ROOT / "scratch" / "maedge" / "settle.tsv"
TSV = ROOT / "scratch" / "maedge" / "settle-c34.tsv"
PREFIX = "SignedDifferenceSets.MaDividedRows"
LINE = re.compile(r"(N\d+) SDS\((\d+),(\d+),(-?\d+),\[([\d,]+)\]\) \d+ KILL (\d+) (\d+) \[([\d,]+)\] (\d+)$")


def cert(ms, k, lam, p, j, e):
    """`MaDivCert` fields from the kill's p, j and H' = ∏ ZMod eₜ (one factor carries p^(j−1))."""
    v, n = math.prod(ms), k - lam
    si = max(range(len(e)), key=lambda t: vp(e[t], p))
    d = [x // p ** vp(x, p) for x in e]
    pj, r = p ** j, p ** (j - 1)
    src = [t for t, x in enumerate(d) if x > 1]
    ks = [d[t] for t in src] or [1]
    srcs = src or [si]
    A = [[0] * si + [1]] + [[0] * t + [1] for t in srcs]
    P = [[0] * si + [crt(1, pj, 0, d[si])]]
    for t, x in zip(srcs, ks):
        P.append([0] * t + [crt(1, x, 0, pj) if t == si else 1 % x])
    i = conj_exp(p, math.lcm(*ks))
    ee = vp(n, p)
    c = v // (r * p * math.prod(ks))
    s = math.isqrt(k + lam * (v - 1))
    kk = k // p if (k // p - k) % 2 == 0 else k // p - 1
    Q, t_, s1 = (k + lam * (p * c - 1)) // (p * p), lam * c // p, s // p
    return dict(p=p, r=r, i=i, e=ee, b=ee // 2, ks=ks, A=A, P=P, k1=kk, Q=Q, t=t_, s1=s1, c=c, s=s)


def valid(ms, k, lam, x, pairs):
    """Mirror of `MaDivCert.Valid`."""
    p, r, ks = x["p"], x["r"], x["ks"]
    v, h = math.prod(ms), r * p * math.prod(ks)
    c = v // h if v % h == 0 else None
    return (is_prime_td(p) and p != 2 and r > 0 and x["i"] > 0 and ks != [] and all((p ** x["i"] + 1) % d == 0 for d in ks)
            and map_ok(ms, [r * p] + ks, x["A"]) and surj_cert(ms, [r * p] + ks, x["A"], x["P"]) and c is not None
            and (k - lam) % p ** x["e"] == 0 and 2 * x["b"] <= x["e"] and x["b"] > 0
            and p * p * x["Q"] == k + lam * (p * c - 1) and p * x["t"] == lam * c
            and (p * x["s1"]) ** 2 == k + lam * (v - 1) and k < p * (x["k1"] + 2) and (k - x["k1"]) % 2 == 0
            and (p, r) in pairs)


def write_row(rid, ms, k, lam, x):
    v = math.prod(ms)
    group = " × ".join(f"ZMod {m}" for m in ms)
    lam_l = f"({lam})" if lam < 0 else str(lam)
    qf = [x["r"]] + x["ks"]
    grp = f"Grp {lst(qf)}"
    certt = (f"⟨{x['p']}, {x['r']}, {x['i']}, {x['e']}, {x['b']}, {lst(x['ks'])},\n"
             f"      {lst([lst(a) for a in x['A']])},\n"
             f"      {lst([lst(a) for a in x['P']])},\n"
             f"      {x['k1']}, {x['Q']}, {x['t']}, {x['s1']}⟩")
    header = f"""/-- The factors of the divided quotient `{grp}` are positive. -/
theorem hpos : ∀ m ∈ {lst(qf)}, 0 < m := by decide
"""
    doc = (f"Open in Gordon's table (`SDS({v},{k},{lam},{lst(ms).replace(' ', '')})`, 2026-11-05).\n"
           f"C34 on the Ma quotient `ZMod {x['r'] * x['p']} × Grp {lst(x['ks'])}` (`p = {x['p']}`, `b = {x['b']}`):\n"
           f"the coset sums along `{grp}`\n(fibres {x['p'] * x['c']}) are divisible by {x['p']}, and `noVector` finds no `Z = W/{x['p']}` with "
           f"`|Z| ≤ {x['c']}`, square sum {x['Q']},\nautocorrelation {x['t']}, sum ±{x['s1']} and absolute sum at most "
           f"{x['k1']}. Generated by `solver/madividedrows.py`.")
    theorem = f"""/-- N{rid}: no SDS ({v}, {k}, {lam}) in `{group}`. -/
theorem not_hasSDS : ¬ HasSDS ({group}) {k} {lam_l} :=
  MaDivCert.not_hasSDS (w := ⟨{rid}, {lst(ms)}, {k}, {lam_l}⟩)
    (c := {certt}) (by decide +kernel) hpos _"""
    write_search(f"N{rid}", PREFIX, ["SignedDifferenceSets.MaDivided"], f"N{rid}: no ({v}, {k}, {lam}) SDS in {group} (C34)",
                 doc, header, f"@Indexed.size ({grp}) _ (Grp.indexed _ hpos)",
                 f"@Indexed.addIdx ({grp}) _ (Grp.indexed _ hpos)",
                 f"({x['c']} : ℕ) ({x['Q']} : ℤ) ({x['t']} : ℤ) ({x['k1']} : ℕ) {x['s1']}",
                 "the divided quotient and the subtree check", "row's divided search arguments (those `MaDivCert.not_hasSDS` asks for)",
                 math.prod(qf), x["c"], x["Q"], x["s1"], theorem, tool="solver/madividedrows.py",
                 split_nodes=BATCH_NODES)


def main(wanted):
    pairs = ma_pairs()
    c33 = {line.split("\t")[0] for line in C33.read_text(encoding="utf-8").splitlines() if line.strip()}
    rows = []
    for line in KILLS.read_text(encoding="utf-8").splitlines():
        m = LINE.match(line)
        if not m:
            continue
        rid, v, k, lam, ms, p, j, e, _ = m.groups()
        p, j = int(p), int(j)
        if rid in c33 or p == 2 or rid in SKIP or (wanted and rid not in wanted):
            continue
        ms, e = [int(t) for t in ms.split(",")], [int(t) for t in e.split(",")]
        x = cert(ms, int(k), int(lam), p, j, e)
        assert valid(ms, int(k), int(lam), x, pairs), (rid, x)
        rows.append((rid, ms, int(k), int(lam), x))
    (ROOT / "lean" / "SignedDifferenceSets" / "MaDividedRows").mkdir(exist_ok=True)
    for rid, ms, k, lam, x in rows:
        write_row(rid[1:], ms, k, lam, x)
    if not wanted:
        TSV.write_text("".join(f"{rid}\tnone\tC34 (divided contraction below a Ma quotient); MaDividedRows\t"
                               f"{PREFIX}.{rid}.not_hasSDS\n" for rid, *_ in rows), encoding="utf-8", newline="\n")
    print(len(rows), "rows:", " ".join(r[0] for r in rows))


if __name__ == "__main__":
    main(set(sys.argv[1:]))
