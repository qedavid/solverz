"""Rows killed by C33 (Ma's lemma at its edge: p | lambda c), written as Lean.

`maedgerows.py`: for each open row of instances.csv, looks for a prime p with b = v_p(k - lambda) // 2 >= 1 and a
cyclic quotient ZMod (p^j), j >= 2, of one factor of its group, (p, p^(j-1)) among `MaRows.maPairs`, K trivial, and
c = v / p^j with p not dividing lambda c (so the Sylow p-subgroup is cyclic of order p^j). The certificate takes the
least p^(j-1). Writes lean/SignedDifferenceSets/MaEdgeRows.lean (the rows, one `decide +kernel`, a theorem per row)
and scratch/maedge/settle.tsv. Mirrors `MaEdgeCert.Kills`. Standard library only; nothing is written on import.
"""
import csv
import math
from pathlib import Path

from macombrows import group, ma_pairs
from marows import KEY, OPEN, conj_exp, crt, is_prime_td, lst, map_ok, primes_of, surj_cert, vp

ROOT = Path(__file__).resolve().parent.parent
LEAN = ROOT / "lean" / "SignedDifferenceSets"
OUT = LEAN / "MaEdgeRows.lean"
TSV = ROOT / "scratch" / "maedge" / "settle.tsv"


def kills(ms, k, lam, c, pairs):
    """Mirror of `MaEdgeCert.Kills`."""
    p, r, i, e, b, ks, A, P = c
    ds, h, v = [r * p] + ks, r * p * math.prod(ks), math.prod(ms)
    return (is_prime_td(p) and r > 1 and i > 0 and ks != [] and all((p ** i + 1) % d == 0 for d in ks)
            and map_ok(ms, ds, A) and surj_cert(ms, ds, A, P) and v % h == 0
            and (k - lam) % p ** e == 0 and 2 * b <= e and b > 0 and (lam * (v // h)) % p != 0
            and (p, r) in pairs)


def cert(ms, k, lam, pairs):
    n = k - lam
    if n <= 0:
        return None
    best = None
    for p in primes_of(n):
        e = vp(n, p)
        b = e // 2
        if b == 0:
            continue
        for s, m in enumerate(ms):
            for j in range(2, vp(m, p) + 1):
                r, pj = p ** (j - 1), p ** j
                A = [[0] * s + [1], [0] * s + [1]]
                P = [[0] * s + [crt(1, pj, 0, 1)], [0] * s + [crt(1, 1, 0, pj)]]
                c = (p, r, conj_exp(p, 1), e, b, [1], A, P)
                if kills(ms, k, lam, c, pairs) and (best is None or r < best[1]):
                    best = (c, r)
    return best[0] if best else None


def entry(rid, ms, k, lam, c):
    p, r, i, e, b, ks, A, P = c
    lam_l = f"({lam})" if lam < 0 else str(lam)
    return (f"(⟨{rid}, {lst(ms)}, {k}, {lam_l}⟩,\n"
            f"    ⟨{p}, {r}, {i}, {e}, {b}, {lst(ks)},\n"
            f"      {lst([lst(a) for a in A])}, {lst([lst(x) for x in P])}⟩)")


def row_theorem(rid, ms, k, lam, c, text):
    p, r, _, _, b, ks, _, _ = c
    v = math.prod(ms)
    return f"""/-- N{rid}: `SDS({v}, {k}, {lam})` in `{group(ms)}`; `H = ZMod {r * p}`, `c = {v // (r * p)}`,
`p = {p}`, `b = {b}`, `p ∤ λ c`. -/
theorem n{rid}_not_hasSDS : ¬ HasSDS ({group(ms)}) {k} {f"({lam})" if lam < 0 else lam} :=
  not_hasSDS_of_mem_maEdgeRows (x := {text.replace(chr(10), chr(10) + "  ")}) (by decide +kernel) _
"""


def main():
    pairs = ma_pairs()
    rows = []
    for row in csv.DictReader(open(ROOT / "instances.csv", encoding="utf-8")):
        if row["status"] != OPEN:
            continue
        m = KEY.fullmatch(row["key"])
        v, k, lam = map(int, m.groups()[:3])
        ms = [int(x) for x in m.group(4).split(",")]
        c = cert(ms, k, lam, pairs)
        if c:
            rows.append((int(row["id"][1:]), ms, k, lam, c))
    body = ",\n".join("  " + entry(*x) for x in rows)
    thms = "\n".join(row_theorem(*x, entry(*x)) for x in rows)
    OUT.write_text(f"""module

public import SignedDifferenceSets.MaEdge

/-!
# Rows killed by C33 (Ma's lemma at its edge)

{len(rows)} open rows with `p² ∣ k − λ`, a cyclic quotient `ZMod (p^j)`, `j ≥ 2`,
and `p ∤ λ c`, `c = v / p^j`, checked by `MaEdgeCert.Kills` in one `decide +kernel`;
generated by `solver/maedgerows.py`.
-/

@[expose] public section

namespace SignedDifferenceSets.MaEdgeRows

/-- Rows and certificates. -/
def maEdgeRows : List (Row × MaEdgeCert) := [
{body}]

set_option maxRecDepth 100000 in
theorem maEdgeRows_kills : ∀ x ∈ maEdgeRows, x.2.Kills x.1 := by decide +kernel

/-- No row of `maEdgeRows` has an SDS. -/
theorem not_hasSDS_of_mem_maEdgeRows {{x : Row × MaEdgeCert}} (hx : x ∈ maEdgeRows)
    (inst : Fintype (Grp x.1.ms)) : ¬ @HasSDS (Grp x.1.ms) _ inst x.1.k x.1.lam :=
  MaEdgeCert.not_hasSDS (maEdgeRows_kills x hx) inst

{thms}
end SignedDifferenceSets.MaEdgeRows
""", encoding="utf-8", newline="\n")
    TSV.parent.mkdir(parents=True, exist_ok=True)
    TSV.write_text("".join(f"N{x[0]}\tnone\tC33 (Ma's lemma at its edge, p ∤ λc); MaEdgeRows\t"
                           f"SignedDifferenceSets.MaEdgeRows.n{x[0]}_not_hasSDS\n" for x in rows),
                   encoding="utf-8", newline="\n")
    print(len(rows), "rows:", " ".join(f"N{x[0]}" for x in rows))


if __name__ == "__main__":
    main()
