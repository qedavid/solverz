"""Rows killed by C38 with no residue primes (M = 1) whose searches are too large for one kernel check, written as Lean.

`madividedsplitrows.py`: the p = 2 kills of `x_ma_divided` (`scratch/x_ma_divided_10m.out`) that C38's residue does not
shrink; rebuilds each certificate as `madividedresrows.py` with `qs = []` (`MaDivResCert.Valid` mirrored), and writes,
under `lean/SignedDifferenceSets/MaDividedSplitRows/`, one search module `N<id>B<k'>.lean` per bound (`noVector`, split on
two levels by `answer.write_search_tree`) and the row module `N<id>.lean` (`MaDivResCert.not_hasSDS_noVector`); the
settle list `scratch/maedge/settle-c38s.tsv`. Standard library only; nothing is written on import.
"""
import math
from pathlib import Path

from answer import BATCH_NODES, LEAN_DIR, write_module, write_search
from macombrows import ma_pairs
from madividedresrows import cert, valid
from marows import lst

ROOT = Path(__file__).resolve().parent.parent
TSV = ROOT / "scratch" / "maedge" / "settle-c38s.tsv"
PREFIX = "SignedDifferenceSets.MaDividedSplitRows"
# id: (group, p, j, H', split depth, group depth); N752: 7.7M nodes, 109 groups of at most 255 prefixes
ROWS = {"N752": ([2, 32], 58, 22, 2, 5, [1, 16], "8", "4")}


def write_row(rid, ms, k, lam, x, depth, top_depth):
    v = math.prod(ms)
    group = " × ".join(f"ZMod {m}" for m in ms)
    lam_l = f"({lam})" if lam < 0 else str(lam)
    qf = [x["r"]] + x["ks"]
    grp = f"Grp {lst(qf)}"
    header = f"""/-- The factors of the divided quotient `{grp}` are positive. -/
theorem hpos : ∀ m ∈ {lst(qf)}, 0 < m := by decide
"""
    size, add = f"@Indexed.size ({grp}) _ (Grp.indexed _ hpos)", f"@Indexed.addIdx ({grp}) _ (Grp.indexed _ hpos)"
    names = []
    for kk in x["bounds"]:
        args = f"({x['c']} : ℕ) ({x['Q']} : ℤ) ({x['t']} : ℤ) ({kk} : ℕ) {x['s1']}"
        name = f"N{rid}B{kk}"
        names.append(name)
        theorem = f"""/-- N{rid}: the divided search with absolute-sum bound {kk} finds no vector. -/
theorem search :
    noVector ({size})
      ({add})
      {args} = true :="""
        write_search(name, PREFIX, ["SignedDifferenceSets.MaDividedSplit"],
                     f"N{rid}: the C38 search with bound {kk}",
                     f"C38 without residue primes for N{rid} (`SDS({v},{k},{lam})` in `{group}`):\n"
                     f"no vector `Z` on `{grp}` with `|Z| ≤ {x['c']}`, square sum {x['Q']}, autocorrelation {x['t']},\n"
                     f"sum ±{x['s1']} and absolute sum at most {kk} (parity of {kk}).\n"
                     f"Generated by `solver/madividedsplitrows.py`.",
                     header, size, add, args, "the divided quotient and the subtree check",
                     "bound's search arguments", math.prod(qf), x["c"], x["Q"], x["s1"], theorem,
                     tool="solver/madividedsplitrows.py", split_nodes=BATCH_NODES, depth=depth, top_depth=top_depth)
    certt = (f"⟨{x['p']}, {x['r']}, {x['i']}, {x['e']}, {x['b']}, {lst(x['ks'])},\n"
             f"      {lst([lst(a) for a in x['A']])},\n"
             f"      {lst([lst(a) for a in x['P']])},\n"
             f"      {lst(x['bounds'])}, {x['Q']}, {x['t']}, {x['s1']}, []⟩")
    cases = "rcases hk' with rfl | rfl" if len(names) == 2 else "subst hk'"
    exacts = "\n".join(f"      · exact {PREFIX}.{nm}.search" for nm in names) if len(names) == 2 else \
        f"      exact {PREFIX}.{names[0]}.search"
    doc = (f"Open in Gordon's table (`SDS({v},{k},{lam},{lst(ms).replace(' ', '')})`, 2026-11-05).\n"
           f"C38 with no residue primes on the Ma quotient `ZMod {x['r'] * x['p']} × Grp {lst(x['ks'])}` "
           f"(`p = {x['p']}`, `b = {x['b']}`):\nthe coset sums `W` on `{grp}` (fibres {x['p'] * x['c']}) are divisible "
           f"by {x['p']}, and no `Z = W/{x['p']}` exists\nfor any bound in {lst(x['bounds'])} (`{', '.join(names)}`). "
           f"Generated by `solver/madividedsplitrows.py`.")
    write_module(f"N{rid}", ["SignedDifferenceSets.MaDividedSplit"] + [f"{PREFIX}.{nm}" for nm in names],
                 f"N{rid}: no ({v}, {k}, {lam}) SDS in {group} (C38)", doc,
                 f"""{header}
/-- N{rid}: no SDS ({v}, {k}, {lam}) in `{group}`. -/
theorem not_hasSDS : ¬ HasSDS ({group}) {k} {lam_l} :=
  MaDivResCert.not_hasSDS_noVector (w := ⟨{rid}, {lst(ms)}, {k}, {lam_l}⟩)
    (c := {certt}) (by decide +kernel) rfl hpos _
    (fun k' hk' => by
      simp only [List.mem_cons, List.not_mem_nil, or_false] at hk'
      {cases}
{exacts})""", ns=f"{PREFIX}.N{rid}", prefix=PREFIX)


def main():
    pairs = ma_pairs()
    (LEAN_DIR / PREFIX.replace(".", "/")).mkdir(parents=True, exist_ok=True)
    for rid, (ms, k, lam, p, j, e, depth, top_depth) in ROWS.items():
        x = dict(cert(ms, k, lam, p, j, e), qs=[], M=1)
        assert valid(ms, k, lam, x, pairs), (rid, x)
        write_row(rid[1:], ms, k, lam, x, depth, top_depth)
    TSV.write_text("".join(f"{rid}\tnone\tC38 (divided search below a Ma quotient, no residue); MaDividedSplitRows\t"
                           f"{PREFIX}.{rid}.not_hasSDS\n" for rid in ROWS), encoding="utf-8", newline="\n")
    print(len(ROWS), "rows:", " ".join(ROWS))


if __name__ == "__main__":
    main()
