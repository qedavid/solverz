"""I23 on a quotient, centred rows without a multiplier: tomoquot.py with the last coordinate solved from the sum.

tomolast.py <id>[:p] [...] [--test]: as tomoquot.py (which is imported, not changed), but the vector listing is
checked by inPartL / belowInL (TomographyLast.lean: goIn whose last level tries only x = s - sum), which imply
inPart / belowIn; the mirrors count goInL's nodes, so parts and splits are sized for it. Writes
lean/SignedDifferenceSets/TomographyQuotRows/N<id>.lean. --test: verdicts and counts only.
"""
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import tomoquot as Q  # noqa: E402
import tomorows as T  # noqa: E402


def go_in_last(p, c, Qs, t, k, s, top, rem, pre, sm, sq, ab, out, cnt):
    """Mirror of goInL; appends the listed leaves to out, counts calls in cnt[0]."""
    cnt[0] += 1
    if rem == 0:
        if T.leaf_ok(p, Qs, t, k, s, pre, sm, sq, ab):
            out.append(tuple(pre))
        return
    if rem == 1:
        x = s - sm
        if top < abs(x):
            return
        go_in_last(p, c, Qs, t, k, s, top, 0, pre + [x], sm + x, sq + x * x, ab + abs(x), out, cnt)
        return
    if T.cut(c, Qs, s, rem, sm, sq):
        return
    for x in range(-top, top + 1):
        if Qs - sq < x * x:
            continue
        go_in_last(p, c, Qs, t, k, s, top, rem - 1, pre + [x], sm + x, sq + x * x, ab + abs(x), out, cnt)


def in_search(p, C, k, lam, s):
    """Mirror of inPartL over all first coordinates: V0 and the node count per first coordinate."""
    Qs, t = k + lam * (C - 1), lam * C
    out, per = [], {}
    if T.cut(C, Qs, s, p, 0, 0):
        return out, per
    for x in range(-C, C + 1):
        cnt = [0]
        if not Qs < x * x:
            go_in_last(p, C, Qs, t, k, s, abs(x), p - 1, [x], x, x * x, abs(x), out, cnt)
        per[x] = cnt[0]
    return out, per


def below_nodes(p, C, k, lam, s, q):
    """Mirror of belowInL's node count for the prefix q."""
    Qs, t = k + lam * (C - 1), lam * C
    cnt, out = [0], []
    go_in_last(p, C, Qs, t, k, s, abs(q[0]), p - len(q), list(q), sum(q), sum(x * x for x in q),
               sum(abs(x) for x in q), out, cnt)
    return cnt[0]


def to_last(text):
    """tomoquot's row text with the listing checked by inPartL / belowInL."""
    text = text.replace("public import SignedDifferenceSets.TomographyQuot\n",
                        "public import SignedDifferenceSets.TomographyQuot\n"
                        "public import SignedDifferenceSets.TomographyLast\n", 1)
    text = text.replace("Generated by `solver/tomoquot.py`.",
                        "The listing is checked with the last coordinate solved from the sum (`inPartL`,\n"
                        "`belowInL`). Generated by `solver/tomolast.py`.", 1)
    # unsplit parts: `inPart … = true := by decide +kernel` -> `inPart_of_inPartL (by decide +kernel)`
    text, n1 = re.subn(r"(theorem vpart\d+ : inPart (?:(?!\n\n).)*?= true) := by\n  decide \+kernel\n",
                       r"\1 :=\n  inPart_of_inPartL (by decide +kernel)\n", text, flags=re.S)
    # split parts: the prefixes are checked by belowInL
    text, n2 = re.subn(r"(theorem below\d+_\d+ :\n    \(pre\d+_\d+\.all fun q => )belowIn ", r"\1belowInL ", text)
    text = re.sub(r"exact List\.all_eq_true\.1 (below\d+_\d+) q (h|hq)\n",
                  r"exact belowIn_of_belowInL (List.all_eq_true.1 \1 q \2)\n", text)
    return text


def main():
    test = "--test" in sys.argv
    # smaller kernel checks (env VSLICE, default 8000 goInL nodes): about 4.5 GB peak instead of 6
    T.VSLICE = Q.VSLICE = int(os.environ.get("VSLICE", 8000))
    Q.VSPLIT = Q.VSLICE
    Q.in_search = in_search
    Q.below_nodes = below_nodes
    for arg in [x for x in sys.argv[1:] if not x.startswith("--")]:
        id_, _, p = arg.partition(":")
        a = Q.analyse(id_, int(p) if p else None)
        assert a["t"] == 1 and not a["nc"], (id_, "tomolast.py is for centred rows without a multiplier")
        print(id_, (a["v"], a["k"], a["lam"]), a["ms"], "p", a["p"], "c", a["c"], "s", a["s"], "|V0|", len(a["V0"]),
              "|W|", len(a["W"]), "vnodes", a["vnodes"], "pt", a["pt"], "tnodes", a.get("tnodes"),
              "KILLED" if a["killed"] else "FOUND", flush=True)
        if not test and a["killed"]:
            path = Q.write_row(a)
            text = to_last(open(path, encoding="utf-8").read())
            open(path, "w", encoding="utf-8", newline="\n").write(text)
            for i, line in enumerate(text.split("\n"), 1):
                assert len(line) <= 100, (path, i, len(line))
            print("  wrote", path, flush=True)


if __name__ == "__main__":
    main()
