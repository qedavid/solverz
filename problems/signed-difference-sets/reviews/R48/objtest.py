"""Check C42's identities on every known set in objects/ with a quotient Z2 x Z2 x K, K = Z_q (q = 1..6).
For each onto phi (all, or a random sample when too many): z, d1..d3; autocorr(d_i) = n*delta, d_i = z mod 2,
z+d1+d2+d3 = 0 mod 4 (= 4*W(0,h)), z's C3 demands; for q = 3 also that z survives the residue clash (not killed)."""
import sys, re, math, random, itertools, glob, os
sys.path.insert(0, os.path.dirname(__file__))
from kill import zs_alive
random.seed(1)
OBJ = sys.argv[1]
MAXHOM = 400

def load(f):
    lines = open(f, encoding='utf-8').read().split('\n')
    m = re.match(r'(\S+) \((\d+),(\d+),(-?\d+)\)', lines[0])
    ms = [int(x[1:]) for x in m.group(1).split('x')]
    v, k, lam = int(m.group(2)), int(m.group(3)), int(m.group(4))
    D = {}
    for ln in lines[1:]:
        p = ln.split()
        if not p: continue
        D[tuple(int(x) for x in p[:-1])] = 1 if p[-1] == '+' else -1
    return ms, v, k, lam, D

def gen_images(ms, q):
    """Per generator, the allowed images (a,b,c) in Z2 x Z2 x Zq with m*(a,b,c) = 0."""
    out = []
    for m in ms:
        imgs = [(a, b, c) for a in range(2) for b in range(2) for c in range(q)
                if (m*a) % 2 == 0 and (m*b) % 2 == 0 and (m*c) % q == 0]
        out.append(imgs)
    return out

def onto(ms, imgs):
    # subgroup generated by the images equals Z2 x Z2 x Zq: check its size
    span = {(0, 0, 0)}
    frontier = [(0, 0, 0)]
    while frontier:
        x = frontier.pop()
        for g in imgs:
            y = ((x[0]+g[0]) % 2, (x[1]+g[1]) % 2, (x[2]+g[2]) % Q)
            if y not in span: span.add(y); frontier.append(y)
    return len(span) == 4*Q

def check(ms, v, k, lam, D, q):
    global Q; Q = q
    n = k - lam; S = k + lam*(v-1); s = math.isqrt(S)
    choices = gen_images(ms, q)
    total = math.prod(len(c) for c in choices)
    homs = itertools.product(*choices) if total <= MAXHOM else (tuple(random.choice(c) for c in choices) for _ in range(MAXHOM))
    tested = bad = 0
    elems = list(D.items())
    for imgs in homs:
        if not onto(ms, imgs): continue
        tested += 1
        z = [0]*q; d = [[0]*q for _ in range(3)]
        W0 = [0]*q
        for x, sg in elems:
            a = sum(xi*g[0] for xi, g in zip(x, imgs)) % 2
            b = sum(xi*g[1] for xi, g in zip(x, imgs)) % 2
            c = sum(xi*g[2] for xi, g in zip(x, imgs)) % q
            z[c] += sg
            d[0][c] += sg*(-1)**a; d[1][c] += sg*(-1)**b; d[2][c] += sg*(-1)**(a+b)
            if a == 0 and b == 0: W0[c] += sg
        ok = True
        for di in d:
            for g in range(q):
                ac = sum(di[h]*di[(h+g) % q] for h in range(q))
                if ac != (n if g == 0 else 0): ok = False
            if any((di[h]-z[h]) % 2 for h in range(q)): ok = False
        for h in range(q):
            if z[h]+d[0][h]+d[1][h]+d[2][h] != 4*W0[h]: ok = False
        if sum(x*x for x in z) != k + lam*(v//q - 1) or sum(z)**2 != S: ok = False
        if q == 3:
            _, Z, Dres, alive = zs_alive(n, s, k + lam*(v//3 - 1))
            if tuple(z) not in [tuple(a) for a in alive]: ok = False
            if any(tuple(x % 4 for x in di) not in Dres for di in d): ok = False
        if not ok: bad += 1
    return tested, bad

for f in sorted(glob.glob(OBJ + '/O*.txt'), key=lambda p: int(re.search(r'O(\d+)', p).group(1))):
    ms, v, k, lam, D = load(f)
    if sum(1 for m in ms if m % 2 == 0) < 2: continue
    res = []
    for q in range(1, 7):
        if v % (4*q): continue
        t, b = check(ms, v, k, lam, D, q)
        if t: res.append(f'q={q}: {t} onto, {b} bad')
    print(os.path.basename(f), ms, (v, k, lam), '; '.join(res))
