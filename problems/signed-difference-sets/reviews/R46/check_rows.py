"""Independent recheck of the 66 certificates: hypotheses recomputed from instances.csv, the map checked
(well defined, onto), and (count rows) a DP over value multisets without the absolute-sum bound. Own code."""
import math, itertools, sys
import numpy as np
import rowparse as R

def isprime(x): return x > 1 and all(x % d for d in range(2, int(x**.5) + 1))
def vp(x, p):
    c = 0
    while x and x % p == 0: x //= p; c += 1
    return c
def ispow(r, p):
    while r % p == 0: r //= p
    return r == 1

def map_ok(ms, tg, A):
    """x -> (sum_i A[j][i] x_i mod tg[j])_j well defined on prod Z_ms and onto prod Z_tg."""
    A = [row + [0] * (len(ms) - len(row)) for row in A]
    if len(A) != len(tg): return False, "len"
    for j, row in enumerate(A):
        for i, a in enumerate(row):
            if (a * ms[i]) % tg[j]: return False, "not well defined"
    # image subgroup generated by the columns; onto iff its size is prod tg
    gens = [tuple(A[j][i] % tg[j] for j in range(len(tg))) for i in range(len(ms))]
    size = math.prod(tg)
    seen = {tuple([0] * len(tg))}; frontier = list(seen)
    while frontier:
        nf = []
        for x in frontier:
            for g in gens:
                y = tuple((x[j] + g[j]) % tg[j] for j in range(len(tg)))
                if y not in seen: seen.add(y); nf.append(y)
        frontier = nf
        if len(seen) > size: break
    return len(seen) == size, len(seen)

def min_nonzero(c, Q, s):
    """min number of nonzero integers in [-c, c] with square sum Q and sum s (None if impossible)."""
    INF = 10**9
    off = Q
    best = np.full((Q + 1, 2 * Q + 1), INF, dtype=np.int64)
    best[0, off] = 0
    for q in range(1, Q + 1):
        for m in range(1, c + 1):
            if m * m > q: break
            for x in (m, -m):
                prev = best[q - m * m]
                # best[q][S] = min(prev[S - x] + 1)
                if x > 0: best[q, x:] = np.minimum(best[q, x:], prev[:-x] + 1)
                else: best[q, :x] = np.minimum(best[q, :x], prev[-x:] + 1)
    if abs(s) > Q: return None
    v = best[Q, off + s]
    return None if v >= INF else int(v)

def check(name, sub, r, I):
    inst = I[name]; v, k, lam, ms = inst["v"], inst["k"], inst["lam"], inst["ms"]
    n = k - lam
    C = r["c"]
    if sub == "MaCountRows":
        p, rr, i, e, b, l, ks, A, P, amax, Q, s1 = C
    else:
        p, rr, i, e, b, ks, A, P, bounds, Q, t, s1, qs = C; l = 1
    bad = []
    if not isprime(p): bad.append("p")
    if not ispow(rr, p): bad.append("r not p-power")
    if n % p**e: bad.append("p^e|n")
    if not (1 <= l <= b and 2 * b <= e): bad.append("b")
    if any((p**i + 1) % d for d in ks): bad.append("selfconj")
    Kord = math.prod(ks); Hq = rr * p**l * Kord
    if v % Hq: bad.append("index")
    c = v // Hq
    ok, why = map_ok(ms, [rr * p**l] + ks, A)
    if not ok: bad.append(f"map {why}")
    if (k + lam * (p**l * c - 1)) != p**(2 * l) * Q: bad.append("Q")
    S2 = k + lam * (v - 1)
    s = math.isqrt(S2)
    if s * s != S2 or s % p**l or abs(s1) * p**l != s: bad.append("s'")
    N = rr * Kord
    res = dict(name=name, sub=sub, p=p, l=l, r=rr, ks=ks, c=c, N=N, Q=Q, s1=s1, bad=bad, e=e, b=b, n=n)
    if sub == "MaCountRows":
        if not (k < p**l * (amax + 1)): bad.append("amax")
        res["amax"] = amax
        mn = min_nonzero(c, Q, s1) if Q >= 0 else None
        res["min_nonzero"] = mn
        res["dies"] = (mn is None) or (mn > N) or (Q - s1) % 2 != 0
    else:
        M = 1
        for (q, iq, jq) in qs:
            M *= q**jq
            if not isprime(q) or q == p or Hq % q == 0 and False: bad.append("q")
            if (N % q) == 0: bad.append("q | H'")
            if (p * N) % q == 0: bad.append("q | rp prod ks")
            if (q**iq + 1) % rr or any((q**iq + 1) % d for d in ks): bad.append("q selfconj")
            if n % q**(2 * jq): bad.append("q^2j|n")
        res.update(M=M, t=t, bounds=bounds, qs=qs)
        if p * t != lam * c: bad.append("t")
        # bounds cover every absolute sum A with pA <= k, k - pA even
        for Aa in range(k + 1):
            if p * Aa <= k and (k - p * Aa) % 2 == 0:
                if not any(Aa <= kk and (kk - Aa) % 2 == 0 for kk in bounds): bad.append(f"bounds {Aa}"); break
    return res

if __name__ == "__main__":
    rs = R.rows(); I = R.instances()
    for (sub, name), r in sorted(rs.items(), key=lambda x: (x[0][0], int(x[0][1][1:]))):
        res = check(name, sub, r, I)
        print(res)
